set mode Oracle;
CREATE TABLE T_LINK (
    LINK_ID   BIGINT      NOT NULL,
    FULL_LINK VARCHAR(1000) NOT NULL,
    CREATED_DATE DATE NOT NULL,
    EXPIRED_DATE DATE,
    PRIMARY KEY (LINK_ID)
);

CREATE SEQUENCE SEQ_LINK_ID MINVALUE 100000 INCREMENT BY 1;

CREATE TABLE T_LINK_HIT_COUNT(
    SHORT_LINK_ID VARCHAR(7) NOT NULL,
    HIT_COUNT BIGINT NOT NULL,
    UPDATED_DATE DATE NOT NULL,
    VERSION BIGINT NOT NULL,
    PRIMARY KEY (SHORT_LINK_ID)
)